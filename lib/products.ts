export const productsByCategory = (category: CategoryId | "all") =>
  category === "all" ? products : products.filter((p) => p.category === category);

export const formatPrice = (value: number, locale: "uk" | "ru" = "ru") =>
  `${value.toLocaleString(locale === "uk" ? "uk-UA" : "ru-RU")} ₴`;

export const formatProductPrice = (p: Product, locale: "uk" | "ru" = "ru") =>
  p.priceFrom ? `${locale === "uk" ? "від" : "от"} ${formatPrice(p.price, locale)}` : formatPrice(p.price, locale);

